#!/usr/bin/env python3
"""Gzips the built web UI and generates the firmware's static file table.

Usage: embed_web.py <vite firmware build dir> <components/webapi/www>

Writes <www>/www_files.c: each file's gzip bytes as a const C array (in .rodata, so in QSPI) and a table of
{url path, start, end, content type, ETag}. Plain C: no assembler or linker step of its own. The ETag is a hash of the
content, so a changed file is never answered 304 from an older copy. Run via `npm run build:firmware`.
"""
import gzip
import hashlib
import os
import sys

TYPES = {
    ".html": "text/html; charset=utf-8",
    ".js": "application/javascript",
    ".css": "text/css",
    ".png": "image/png",
    ".svg": "image/svg+xml",
    ".ico": "image/x-icon",
    ".json": "application/json",
}


def main(src: str, dst: str) -> None:
    os.makedirs(dst, exist_ok=True)
    for old in os.listdir(dst):  # only files this script generated
        if old.endswith(".gz") or old in ("www_files.c", "www_blobs.S"):  # .gz, .S: what earlier versions wrote
            os.remove(os.path.join(dst, old))
    rows = []
    for root, _, files in os.walk(src):
        for name in sorted(files):
            path = os.path.join(root, name)
            url = "/" + os.path.relpath(path, src).replace(os.sep, "/")
            ext = os.path.splitext(name)[1]
            if ext not in TYPES:
                print(f"skip {url} (unknown type)")
                continue
            flat = url[1:].replace("/", "__") + ".gz"
            with open(path, "rb") as f:
                # mtime=0: identical input gives an identical image (reproducible builds).
                gz = gzip.compress(f.read(), compresslevel=9, mtime=0)
            sym = "".join(c if c.isalnum() else "_" for c in flat)
            etag = '\\"' + hashlib.sha256(gz).hexdigest()[:16] + '\\"'
            rows.append((url, sym, TYPES[ext], len(gz), etag, gz))
    rows.sort()
    with open(os.path.join(dst, "www_files.c"), "w") as c:
        c.write("// Generated by tools/embed_web.py. Do not edit.\n")
        c.write('#include "www_files.h"\n')
        for _, sym, _, _, _, gz in rows:
            c.write(f"\nstatic const uint8_t {sym}[{len(gz)}] = {{\n")
            for i in range(0, len(gz), 16):
                c.write("    " + ", ".join(f"0x{b:02x}" for b in gz[i:i + 16]) + ",\n")
            c.write("};\n")
        c.write("\nconst www_file_t www_files[] = {\n")
        for url, sym, ctype, _, etag, _ in rows:
            c.write(f'    {{"{url}", {sym}, {sym} + sizeof {sym}, "{ctype}", "{etag}"}},\n')
        c.write("};\nconst size_t www_file_count = sizeof www_files / sizeof www_files[0];\n")
    total = sum(r[3] for r in rows)
    print(f"embedded {len(rows)} files, {total / 1024:.1f} KiB gzipped")


if __name__ == "__main__":
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    main(sys.argv[1], sys.argv[2])
