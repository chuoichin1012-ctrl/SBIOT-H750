#!/usr/bin/env python3
"""Gzips the built web UI and generates the firmware's static file table.

Usage: embed_web.py <vite firmware build dir> <components/webapi/www>

Writes <www>/<flat-name>.gz for each file, <www>/www_files.c, a table of
{url path, embedded symbol, content type, ETag}, and <www>/www_blobs.S, which puts each .gz in
.rodata with .incbin (assembled with -Wa,-I<www>; objcopy -I binary objects carry no ARM attributes). The ETag is a hash of the
content, so a changed file is never answered 304 from an older copy. Run via `npm run build:firmware`.
"""
import gzip
import hashlib
import os
import sys

TYPES = {
    ".html": "text/html; charset=utf-8",
    ".js": "application/javascript",
    ".css": "text/css",
    ".png": "image/png",
    ".svg": "image/svg+xml",
    ".ico": "image/x-icon",
    ".json": "application/json",
}


def main(src: str, dst: str) -> None:
    os.makedirs(dst, exist_ok=True)
    for old in os.listdir(dst):  # only files this script generated
        if old.endswith(".gz") or old in ("www_files.c", "www_blobs.S"):
            os.remove(os.path.join(dst, old))
    rows = []
    for root, _, files in os.walk(src):
        for name in sorted(files):
            path = os.path.join(root, name)
            url = "/" + os.path.relpath(path, src).replace(os.sep, "/")
            ext = os.path.splitext(name)[1]
            if ext not in TYPES:
                print(f"skip {url} (unknown type)")
                continue
            flat = url[1:].replace("/", "__") + ".gz"
            with open(path, "rb") as f, open(os.path.join(dst, flat), "wb") as out:
                # mtime=0: identical input gives an identical image (reproducible builds).
                gz = gzip.compress(f.read(), compresslevel=9, mtime=0)
                out.write(gz)
            sym = "".join(c if c.isalnum() else "_" for c in flat)
            etag = '\\"' + hashlib.sha256(gz).hexdigest()[:16] + '\\"'
            rows.append((url, sym, TYPES[ext], len(gz), etag))
    rows.sort()
    with open(os.path.join(dst, "www_files.c"), "w") as c:
        c.write("// Generated by firmware/tools/embed_web.py. Do not edit.\n")
        c.write('#include "www_files.h"\n\n')
        for _, sym, _, _, _ in rows:
            c.write(f"extern const uint8_t _binary_{sym}_start[];\nextern const uint8_t _binary_{sym}_end[];\n")
        c.write("\nconst www_file_t www_files[] = {\n")
        for url, sym, ctype, _, etag in rows:
            c.write(f'    {{"{url}", _binary_{sym}_start, _binary_{sym}_end, "{ctype}", "{etag}"}},\n')
        c.write("};\nconst size_t www_file_count = sizeof www_files / sizeof www_files[0];\n")
    with open(os.path.join(dst, "www_blobs.S"), "w") as a:
        a.write("// Generated by firmware/tools/embed_web.py. Do not edit.\n")
        a.write('    .section .rodata.www, "a"\n')
        for url, sym, _, _, _ in rows:
            flat = url[1:].replace("/", "__") + ".gz"
            a.write(f"    .balign 4\n    .global _binary_{sym}_start\n_binary_{sym}_start:\n")
            a.write(f'    .incbin "{flat}"\n    .global _binary_{sym}_end\n_binary_{sym}_end:\n')
    total = sum(r[3] for r in rows)
    print(f"embedded {len(rows)} files, {total / 1024:.1f} KiB gzipped")


if __name__ == "__main__":
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    main(sys.argv[1], sys.argv[2])
